#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_count_comment_lines() {
        let code = "// Comment\nfn main() {}\n// Another comment\n";
        assert_eq!(count_comment_lines(code), 2);
    }

    #[test]
    fn test_count_comment_lines_python() {
        let code = "# Comment\ndef main():\n    # Inline\n    pass\n";
        assert_eq!(count_comment_lines(code), 2);
    }

    #[test]
    fn test_count_comment_lines_empty() {
        let code = "fn main() {}\n";
        assert_eq!(count_comment_lines(code), 0);
    }
}
