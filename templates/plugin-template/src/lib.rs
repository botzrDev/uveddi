// Thread-local storage for plugin state
thread_local! {
    static PLUGIN_STATE: RefCell<Option<PluginState>> = RefCell::new(None);
}

// =====================================================
// Helper Functions
// =====================================================

/// Count lines that appear to be comments
fn count_comment_lines(content: &str) -> u32 {
    content
        .lines()
        .filter(|line| {
            let trimmed = line.trim();
            trimmed.starts_with("//")
                || trimmed.starts_with("#")
                || trimmed.starts_with("/*")
                || trimmed.starts_with("*")
                || trimmed.starts_with("'''")
                || trimmed.starts_with("\"\"\"")
        })
        .count() as u32
}

/// Check if a configuration value should be applied based on config
fn should_apply_config(key: &str) -> bool {
    if let Some(ref state) = *PLUGIN_STATE.borrow() {
        for (k, v) in &state.config.custom_settings {
            if k == key {
                return v == "true" || v == "1" || v == "yes";
            }
        }
    }
    false
}

/// Get a configuration value with a default fallback
fn get_config_value(key: &str, default: &str) -> String {
    if let Some(ref state) = *PLUGIN_STATE.borrow() {
        for (k, v) in &state.config.custom_settings {
            if k == key {
                return v.clone();
            }
        }
    }
    default.to_string()
}

